package com.github.h3yow.serviceobservabilitypipelinejava.obs.correlation;

import java.util.concurrent.atomic.AtomicLong;
import java.util.regex.Pattern;

/**
 * Generation and sanitization of correlation ids.
 *
 * <p>Rules:
 * <ul>
 *   <li>An inbound id is accepted only when it matches a strict charset
 *       ({@code [A-Za-z0-9._:-]}) and fits the configured length. Anything else
 *       (missing, blank, containing whitespace/control chars, too long) is rejected
 *       and replaced by a generated fallback, so a client can never poison logs/MDC.</li>
 *   <li>A generated fallback always starts with {@code auto-}, making it
 *       distinguishable from client-supplied ids. It combines a time component with
 *       a process-global monotonic sequence, which makes it unique even when many
 *       requests enter in the same millisecond on the same JVM.</li>
 * </ul>
 */
public final class CorrelationIds {

    /** Prefix that marks ids generated by this service rather than propagated in. */
    public static final String FALLBACK_PREFIX = "auto-";

    private static final Pattern ALLOWED_INBOUND = Pattern.compile("[A-Za-z0-9._:\\-]{1,128}");

    private static final AtomicLong SEQUENCE = new AtomicLong();

    private CorrelationIds() {
    }

    /**
     * Generates a unique fallback correlation id of the form
     * {@code auto-<time-base36>-<seq-base36>}.
     */
    public static String generateFallback() {
        long seq = SEQUENCE.getAndIncrement();
        return FALLBACK_PREFIX
                + Long.toString(System.nanoTime(), 36)
                + '-'
                + Long.toString(seq, 36);
    }

    /**
     * Validates an inbound correlation id.
     *
     * @param raw       the raw header value, may be {@code null}
     * @param maxLength maximum accepted length (the configured cap)
     * @return the accepted id, or {@code null} when the caller must use a fallback
     */
    public static String sanitizeIncoming(String raw, int maxLength) {
        if (raw == null) {
            return null;
        }
        String trimmed = raw.trim();
        if (trimmed.isEmpty() || trimmed.length() > maxLength || trimmed.length() > 128) {
            return null;
        }
        return ALLOWED_INBOUND.matcher(trimmed).matches() ? trimmed : null;
    }
}
